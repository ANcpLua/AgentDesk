using System.Globalization;
using System.Text.Json.Serialization;
using JetBrains.Annotations;

namespace AgentDesk.Codex;

/// <summary>Account-wide token activity; decimal strings preserve native 64-bit counters in browser clients.</summary>
[UsedImplicitly(ImplicitUseTargetFlags.WithMembers)]
public sealed record CodexTokenActivity(CodexTokenSummary Summary, IReadOnlyList<CodexDailyTokenBucket>? DailyUsageBuckets);

/// <summary>Null means Codex did not report the measurement; zero is a reported measurement.</summary>
[UsedImplicitly(ImplicitUseTargetFlags.WithMembers)]
public sealed record CodexTokenSummary(string? LifetimeTokens, string? PeakDailyTokens,
    string? LongestRunningTurnSec, string? CurrentStreakDays, string? LongestStreakDays);

[UsedImplicitly(ImplicitUseTargetFlags.WithMembers)]
public sealed record CodexDailyTokenBucket(string StartDate, string Tokens);

// codex-cli 0.165.0: v2/GetAccountTokenUsageResponse, AccountTokenUsageSummary and
// AccountTokenUsageDailyBucket, generated by `codex app-server generate-ts --experimental`.
// This read intentionally omits threadId so these are account-wide measurements.
[UsedImplicitly(ImplicitUseTargetFlags.WithMembers)]
internal sealed record NativeTokenActivity(
    [property: JsonRequired] NativeTokenSummary Summary,
    NativeDailyTokenBucket[]? DailyUsageBuckets)
{
    public CodexTokenActivity ToResponse()
    {
        if (Summary is null || DailyUsageBuckets?.Any(bucket => bucket is null || string.IsNullOrWhiteSpace(bucket.StartDate)) == true)
            throw new CodexConnectionException("Codex hat keine lesbaren Token-Aktivitätsdaten geliefert.");
        return new(Summary.ToResponse(), DailyUsageBuckets?.Select(bucket =>
            new CodexDailyTokenBucket(bucket.StartDate, Counter(bucket.Tokens)!)).ToArray());
    }

    internal static string? Counter(long? value)
    {
        if (value < 0)
            throw new CodexConnectionException("Codex hat keine lesbaren Token-Aktivitätsdaten geliefert.");
        return value?.ToString(CultureInfo.InvariantCulture);
    }
}

[UsedImplicitly(ImplicitUseTargetFlags.WithMembers)]
internal sealed record NativeTokenSummary(
    long? LifetimeTokens,
    long? PeakDailyTokens,
    long? LongestRunningTurnSec,
    long? CurrentStreakDays,
    long? LongestStreakDays)
{
    public CodexTokenSummary ToResponse() => new(
        NativeTokenActivity.Counter(LifetimeTokens), NativeTokenActivity.Counter(PeakDailyTokens),
        NativeTokenActivity.Counter(LongestRunningTurnSec), NativeTokenActivity.Counter(CurrentStreakDays),
        NativeTokenActivity.Counter(LongestStreakDays));
}

[UsedImplicitly(ImplicitUseTargetFlags.WithMembers)]
internal sealed record NativeDailyTokenBucket(
    [property: JsonRequired] string StartDate, [property: JsonRequired] long Tokens);
